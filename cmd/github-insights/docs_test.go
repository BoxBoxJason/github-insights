const (
	// updateDocsEnv, when set, makes the generated page tests rewrite the
	// pages instead of comparing them.
	updateDocsEnv = "UPDATE_DOCS"

	// docsContentDir is the documentation pages directory, from this package.
	docsContentDir = "../../docs/content/docs"
	// cliReferenceFile is the generated CLI reference page.
	cliReferenceFile = "cli-reference.md"
	// outputSchemaFile is the generated output schema page.
	outputSchemaFile = "output-schema.md"
	// usageFile is the page documenting every flag.
	usageFile = "usage.md"
	// configurationFile is the page documenting the environment and config.
	configurationFile = "configuration.md"

	// docsFilePermission is the permission of the generated pages.
	docsFilePermission = 0o600
	// docsDirPermission is the permission of the pages directory.
	docsDirPermission = 0o750
)

// envVarPattern finds the environment variables read by the CLI.
var envVarPattern = regexp.MustCompile(`os\.Getenv\("([A-Z][A-Z0-9_]*)"\)`)

// documentedFlagSet returns the CLI flags, defined the way the CLI does.
func documentedFlagSet() *flag.FlagSet {
	flagSet := flag.NewFlagSet("github-insights", flag.ContinueOnError)
	registerFlags(flagSet)

	return flagSet
}

// cliEnvVars returns the environment variables main.go reads.
func cliEnvVars(t *testing.T) []string {
	t.Helper()

	source, err := os.ReadFile("main.go")
	if err != nil {
		t.Fatalf("reading main.go: %v", err)
	}

	matches := envVarPattern.FindAllStringSubmatch(string(source), -1)
	if len(matches) == 0 {
		t.Fatal("found no environment variable in main.go, the pattern is out of date")
	}

	names := make([]string, 0, len(matches))
	for _, match := range matches {
		names = append(names, match[1])
	}

	return names
}

// renderCLIReference renders the help of the CLI as a documentation page.
func renderCLIReference() string {
	var defaults bytes.Buffer

	flagSet := documentedFlagSet()
	flagSet.SetOutput(&defaults)
	flagSet.PrintDefaults()

	var page strings.Builder

	page.WriteString("---\ntitle: CLI reference\ndescription: \"Complete github-insights command-line reference, generated from the flag definitions: every flag, its type and its default.\"\nweight: 70\n---\n\n")
	page.WriteString("<!-- Code generated by TestCLIReference (run `make docs-generate`); DO NOT EDIT. -->\n\n")
	page.WriteString("{{< callout type=\"info\" >}}\nThis page is generated from the CLI definition, so it always matches the released flags.\n{{< /callout >}}\n\n")
	page.WriteString("```text\nUsage of github-insights:\n" + strings.TrimRight(defaults.String(), "\n") + "\n```\n")

	return page.String()
}

// schemaTypeName describes a JSON value type, linking nested objects to
// their section.
func schemaTypeName(fieldType reflect.Type) string {
	switch {
	case fieldType == reflect.TypeFor[time.Time]():
		return "timestamp (RFC 3339)"
	case fieldType.Kind() == reflect.Pointer:
		return schemaTypeName(fieldType.Elem())
	case fieldType.Kind() == reflect.Slice:
		return "array of " + schemaTypeName(fieldType.Elem())
	case fieldType.Kind() == reflect.Struct:
		return "[" + fieldType.Name() + "](#" + strings.ToLower(fieldType.Name()) + ")"
	case fieldType.Kind() == reflect.String:
		return "string"
	case fieldType.Kind() == reflect.Bool:
		return "boolean"
	default:
		return "integer"
	}
}

// nestedStruct returns the object type held by a field, if any.
func nestedStruct(fieldType reflect.Type) (reflect.Type, bool) {
	for fieldType.Kind() == reflect.Pointer || fieldType.Kind() == reflect.Slice {
		fieldType = fieldType.Elem()
	}

	if fieldType.Kind() != reflect.Struct || fieldType == reflect.TypeFor[time.Time]() {
		return nil, false
	}

	return fieldType, true
}

// renderOutputSchema renders the JSON structure of the report files,
// starting from RepoActivity.
func renderOutputSchema() string {
	var page strings.Builder

	page.WriteString("---\ntitle: Output schema\ndescription: \"Field-by-field reference of the github-insights JSON reports, generated from the Go types: RepoActivity and every nested object.\"\nweight: 40\n---\n\n")
	page.WriteString("<!-- Code generated by TestOutputSchema (run `make docs-generate`); DO NOT EDIT. -->\n\n")
	page.WriteString("{{< callout type=\"info\" >}}\nThis page is generated from the Go types the report files are encoded from, so it always matches the actual output.\n{{< /callout >}}\n\n")
	page.WriteString("Every report file holds one [RepoActivity](#repoactivity) object. Fields marked as optional are left out of the file when they are empty.\n")

	queue := []reflect.Type{reflect.TypeFor[collector.RepoActivity]()}
	seen := map[reflect.Type]bool{queue[0]: true}

	for len(queue) > 0 {
		current := queue[0]
		queue = queue[1:]

		page.WriteString("\n## " + current.Name() + "\n\n| Field | Type | Optional |\n| ----- | ---- | -------- |\n")

		for field := range current.Fields() {
			name, options, _ := strings.Cut(field.Tag.Get("json"), ",")
			if name == "" || name == "-" {
				continue
			}

			optional := "no"
			if strings.Contains(options, "omitempty") {
				optional = "yes"
			}

			page.WriteString("| `" + name + "` | " + schemaTypeName(field.Type) + " | " + optional + " |\n")

			nested, ok := nestedStruct(field.Type)
			if ok && !seen[nested] {
				seen[nested] = true
				queue = append(queue, nested)
			}
		}
	}

	return page.String()
}

// checkGeneratedPage compares a generated page with its committed version,
// or rewrites it when UPDATE_DOCS is set.
func checkGeneratedPage(t *testing.T, name, want string) {
	t.Helper()

	path := filepath.Join(docsContentDir, name)

	if os.Getenv(updateDocsEnv) != "" {
		err := os.MkdirAll(filepath.Dir(path), docsDirPermission)
		if err != nil {
			t.Fatalf("creating the docs directory: %v", err)
		}

		err = os.WriteFile(path, []byte(want), docsFilePermission)
		if err != nil {
			t.Fatalf("writing %s: %v", path, err)
		}

		return
	}

	got, err := os.ReadFile(path) //nolint:gosec // path is built from constants
	if err != nil {
		t.Fatalf("reading %s: %v (run `make docs-generate`)", path, err)
	}

	if string(got) != want {
		t.Fatalf("%s is out of date, run `make docs-generate` and commit the result", path)
	}
}

// readDocsPage returns the content of a documentation page.
func readDocsPage(t *testing.T, name string) string {
	t.Helper()

	content, err := os.ReadFile(filepath.Join(docsContentDir, name)) //nolint:gosec // path is built from constants
	if err != nil {
		t.Fatalf("reading the %s documentation page: %v", name, err)
	}

	return string(content)
}

// TestCLIReference fails when the generated CLI reference is stale.
func TestCLIReference(t *testing.T) {
	t.Parallel()

	checkGeneratedPage(t, cliReferenceFile, renderCLIReference())
}

// TestOutputSchema fails when the generated output schema is stale.
func TestOutputSchema(t *testing.T) {
	t.Parallel()

	checkGeneratedPage(t, outputSchemaFile, renderOutputSchema())
}

// TestDocsCoverEveryFlag fails when a flag is missing from the usage page.
func TestDocsCoverEveryFlag(t *testing.T) {
	t.Parallel()

	usage := readDocsPage(t, usageFile)

	documentedFlagSet().VisitAll(func(f *flag.Flag) {
		if !strings.Contains(usage, "| `--"+f.Name+"` |") {
			t.Errorf("flag --%s is not documented in docs/content/docs/%s", f.Name, usageFile)
		}
	})
}

// TestDocsCoverEveryEnvVar fails when an environment variable is missing
// from the configuration page.
func TestDocsCoverEveryEnvVar(t *testing.T) {
	t.Parallel()

	configuration := readDocsPage(t, configurationFile)

	for _, name := range cliEnvVars(t) {
		if !strings.Contains(configuration, "`"+name+"`") {
			t.Errorf("environment variable %s is not documented in docs/content/docs/%s", name, configurationFile)
		}
	}
}

// TestDocsCoverEveryConfigKey fails when a config file key is missing from
// the configuration page.
func TestDocsCoverEveryConfigKey(t *testing.T) {
	t.Parallel()

	configuration := readDocsPage(t, configurationFile)

	for field := range reflect.TypeFor[config.RawConfig]().Fields() {
		name, _, _ := strings.Cut(field.Tag.Get("yaml"), ",")
		if name == "" || name == "-" {
			continue
		}

		if !strings.Contains(configuration, "| `"+name+"` |") {
			t.Errorf("configuration key %s is not documented in docs/content/docs/%s", name, configurationFile)
		}
	}
}
